// Command configgen reads the keys table of spec/design/config.yaml (D-074)
// and writes it as Go data to internal/config/schema/defaults_gen.go. It is
// run by `go generate` from the schema package directory.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"

	"gopkg.in/yaml.v3"
)

const header = "// Code generated by configgen; DO NOT EDIT.\n\n" +
	"package schema\n\n"

type row struct {
	Key     string `yaml:"key"`
	File    string `yaml:"file"`
	Type    string `yaml:"type"`
	Default string `yaml:"default"`
	Source  string `yaml:"source"`
	Phase   string `yaml:"phase"`
}

var (
	knownTypes  = map[string]bool{"string": true, "int": true, "float": true, "bool": true, "duration": true, "path": true, "argv_list": true, "string_list": true, "table_list": true}
	knownFiles  = map[string]bool{"runtime.toml": true, "roles.toml": true, "projects/<p>.toml": true}
	knownPhases = map[string]bool{"": true, "v2": true}
)

func main() {
	specPath := flag.String("spec", "../../../spec/design/config.yaml", "config.yaml path")
	out := flag.String("out", "defaults_gen.go", "output file")
	flag.Parse()
	data, err := os.ReadFile(*specPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "configgen:", err)
		os.Exit(1)
	}
	src, err := generate(data)
	if err != nil {
		fmt.Fprintln(os.Stderr, "configgen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "configgen:", err)
		os.Exit(1)
	}
}

// generate renders defaults_gen.go. Rows keep YAML order.
func generate(specYAML []byte) ([]byte, error) {
	var doc struct {
		Keys []row `yaml:"keys"`
	}
	if err := yaml.Unmarshal(specYAML, &doc); err != nil {
		return nil, fmt.Errorf("parse config.yaml: %w", err)
	}
	if len(doc.Keys) == 0 {
		return nil, fmt.Errorf("config.yaml has no keys table")
	}
	seen := map[string]bool{}
	for _, r := range doc.Keys {
		id := r.File + " " + r.Key
		switch {
		case r.Key == "" || r.Default == "" || r.Source == "":
			return nil, fmt.Errorf("row %q: key, default and source are required", id)
		case !knownFiles[r.File]:
			return nil, fmt.Errorf("row %q: unknown file %q", id, r.File)
		case !knownTypes[r.Type]:
			return nil, fmt.Errorf("row %q: unknown type %q", id, r.Type)
		case !knownPhases[r.Phase]:
			return nil, fmt.Errorf("row %q: unknown phase %q", id, r.Phase)
		case seen[id]:
			return nil, fmt.Errorf("row %q: duplicate", id)
		}
		seen[id] = true
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("// keyRow is one row of the keys table in design/config.yaml (D-074).\n")
	b.WriteString("type keyRow struct{ Key, File, Type, Default, Source, Phase string }\n\n")
	b.WriteString("// keyTable is the keys table, in file order.\n")
	b.WriteString("var keyTable = []keyRow{\n")
	for _, r := range doc.Keys {
		fmt.Fprintf(&b, "{%q, %q, %q, %q, %q, %q},\n", r.Key, r.File, r.Type, r.Default, r.Source, r.Phase)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return src, nil
}
