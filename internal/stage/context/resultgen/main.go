// Command resultgen reads PF-RESULT of spec/design/protocol-run.yaml and writes
// the result.json description given to sessions (D-091) as Go data to
// internal/stage/context/resultdoc_gen.go. It is run by `go generate` from the
// context package directory.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

const header = "// Code generated by resultgen; DO NOT EDIT.\n\n" +
	"package context\n\n"

// RunIDPlaceholder stands for the run_id in the generated examples.
const RunIDPlaceholder = "{{run_id}}"

type field struct {
	Name         string `yaml:"name"`
	Type         string `yaml:"type"`
	Required     bool   `yaml:"required"`
	RequiredWhen string `yaml:"required_when"`
	Value        any    `yaml:"value"`
	Rule         string `yaml:"rule"`
	Note         string `yaml:"note"`
	MinItems     int    `yaml:"min_items"`
	MaxLen       int    `yaml:"max_len"`
}

type example struct {
	Name   string         `yaml:"name"`
	Value  map[string]any `yaml:"value"`
	Expect string         `yaml:"expect"`
}

func main() {
	specPath := flag.String("spec", "../../../spec/design/protocol-run.yaml", "protocol-run.yaml path")
	out := flag.String("out", "resultdoc_gen.go", "output file")
	flag.Parse()
	data, err := os.ReadFile(*specPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "resultgen:", err)
		os.Exit(1)
	}
	src, err := generate(data)
	if err != nil {
		fmt.Fprintln(os.Stderr, "resultgen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "resultgen:", err)
		os.Exit(1)
	}
}

// line describes one field for a reader who has no access to the spec.
func line(f field) string {
	need := "optional"
	switch {
	case f.Required:
		need = "required"
	case f.RequiredWhen != "":
		need = "required when " + f.RequiredWhen
	}
	extra := []string{}
	if f.Value != nil {
		extra = append(extra, fmt.Sprintf("must be %v", f.Value))
	}
	if f.MinItems > 0 {
		extra = append(extra, fmt.Sprintf("at least %d items", f.MinItems))
	}
	if f.MaxLen > 0 {
		extra = append(extra, fmt.Sprintf("at most %d characters", f.MaxLen))
	}
	for _, s := range []string{f.Rule, f.Note} {
		// A rule that points at another spec file means nothing in the
		// sandbox (D-091): leave it out; the example shows the shape.
		if s != "" && !strings.Contains(s, ".yaml") && !strings.Contains(s, "smcheck") {
			extra = append(extra, s)
		}
	}
	s := fmt.Sprintf("- `%s` (%s; %s)", f.Name, f.Type, need)
	if len(extra) > 0 {
		s += ": " + strings.Join(extra, "; ")
	}
	return s
}

// generate renders resultdoc_gen.go. Field lines keep YAML order; examples
// are keyed by the role in their value. Examples marked invalid (expect) are
// not shown to sessions.
func generate(specYAML []byte) ([]byte, error) {
	var doc struct {
		Files []struct {
			ID       string    `yaml:"id"`
			Fields   []field   `yaml:"fields"`
			Examples []example `yaml:"examples"`
		} `yaml:"files"`
	}
	if err := yaml.Unmarshal(specYAML, &doc); err != nil {
		return nil, fmt.Errorf("parse protocol-run.yaml: %w", err)
	}
	var fields []field
	var examples []example
	for _, f := range doc.Files {
		if f.ID == "PF-RESULT" {
			fields, examples = f.Fields, f.Examples
		}
	}
	if len(fields) == 0 {
		return nil, fmt.Errorf("protocol-run.yaml has no PF-RESULT fields")
	}
	byRole := map[string]string{}
	for _, e := range examples {
		if e.Expect != "" {
			continue
		}
		role, _ := e.Value["role"].(string)
		if role == "" {
			return nil, fmt.Errorf("example %q lacks a role", e.Name)
		}
		if _, dup := byRole[role]; dup {
			continue // the first valid example of a role is the one shown
		}
		e.Value["run_id"] = RunIDPlaceholder
		raw, err := json.MarshalIndent(e.Value, "", "  ")
		if err != nil {
			return nil, fmt.Errorf("example %q: %w", e.Name, err)
		}
		byRole[role] = string(raw)
	}
	if len(byRole) == 0 {
		return nil, fmt.Errorf("PF-RESULT has no valid example")
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("// resultFieldLines describe the fields of result.json (PF-RESULT), in spec order.\n")
	b.WriteString("var resultFieldLines = []string{\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "%q,\n", line(f))
	}
	b.WriteString("}\n\n")
	b.WriteString("// resultRunIDPlaceholder stands for the run_id inside resultExamples.\n")
	fmt.Fprintf(&b, "const resultRunIDPlaceholder = %q\n\n", RunIDPlaceholder)
	b.WriteString("// resultExamples maps a role to one valid result.json example.\n")
	b.WriteString("var resultExamples = map[string]string{\n")
	roles := make([]string, 0, len(byRole))
	for r := range byRole {
		roles = append(roles, r)
	}
	sort.Strings(roles)
	for _, r := range roles {
		fmt.Fprintf(&b, "%q: %q,\n", r, byRole[r])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return src, nil
}
