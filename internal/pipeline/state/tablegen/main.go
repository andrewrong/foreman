// Command tablegen reads spec/design/state-machine.yaml and writes the
// transition tables of internal/pipeline/state as Go data (table_gen.go).
// It is run by `go generate` from the state package directory.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/andrewrong/foreman/internal/spec/smcheck"
)

const header = "// Code generated by tablegen; DO NOT EDIT.\n\n" +
	"package state\n\n"

func main() {
	specPath := flag.String("spec", "../../../spec/design/state-machine.yaml", "state-machine.yaml path")
	out := flag.String("out", "table_gen.go", "output file")
	flag.Parse()
	data, err := os.ReadFile(*specPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "tablegen:", err)
		os.Exit(1)
	}
	src, err := generate(data)
	if err != nil {
		fmt.Fprintln(os.Stderr, "tablegen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "tablegen:", err)
		os.Exit(1)
	}
}

// generate renders table_gen.go from the YAML. Output is deterministic: rows
// keep YAML order, map-like data is sorted by key.
func generate(specYAML []byte) ([]byte, error) {
	sp, err := smcheck.Parse(specYAML)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(header)
	w := &writer{b: &b}
	w.dims(sp)
	w.stepTable(sp)
	w.holdTable(sp)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return src, nil
}

type writer struct{ b *bytes.Buffer }

func (w *writer) p(format string, a ...any) { fmt.Fprintf(w.b, format, a...) }

func strs(l []string) string {
	if l == nil {
		return "nil"
	}
	q := make([]string, len(l))
	for i, s := range l {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func guards(g []smcheck.Guard) string {
	if g == nil {
		return "nil"
	}
	q := make([]string, len(g))
	for i, x := range g {
		q[i] = fmt.Sprintf("{%q, %q}", x.Dim, x.Val)
	}
	return "[]guard{" + strings.Join(q, ", ") + "}"
}

func target(t smcheck.Target) string {
	return fmt.Sprintf("target{%q, %q, %q}", t.State, t.Stage, t.Reason)
}

func (w *writer) dims(sp *smcheck.Spec) {
	w.p("// Dimensions of the state machine (dims in state-machine.yaml).\n")
	w.p("var (\n")
	w.p("dimStates = %s\n", strs(sp.States))
	w.p("dimTerminal = %s\n", strs(sp.Terminal))
	w.p("dimEvents = %s\n", strs(sp.Events))
	w.p("dimHoldValues = %s\n", strs(sp.HoldValues))
	w.p(")\n\n")

	w.p("var dimTypes = []typeDef{\n")
	for _, t := range sp.Types {
		w.p("{%q, %s, %s, %q},\n", t.Name, strs(t.Stages), strs(t.RunningStages), t.FirstStage)
	}
	w.p("}\n\n")

	stages := map[string]bool{}
	for _, t := range sp.Types {
		for _, s := range t.Stages {
			stages[s] = true
		}
	}
	var sl []string
	for s := range stages {
		sl = append(sl, s)
	}
	sort.Strings(sl)
	w.p("var dimStages = %s\n\n", strs(sl))

	w.p("var dimWaitingReasons = []waitingReason{\n")
	for _, r := range sp.WaitingReasons {
		w.p("{%q, %s, %s},\n", r.Name, strs(r.Types), strs(r.Stages))
	}
	w.p("}\n\n")

	w.counterMap("dimCounters", sp.Counters)
	w.counterMap("dimReqCounters", sp.ReqCounters)

	enums := append([]smcheck.Enum(nil), sp.GuardEnums...)
	sort.Slice(enums, func(i, j int) bool { return enums[i].Name < enums[j].Name })
	w.p("var dimGuardEnums = map[string][]string{\n")
	for _, e := range enums {
		w.p("%q: %s,\n", e.Name, strs(e.Values))
	}
	w.p("}\n\n")
}

func (w *writer) counterMap(name string, cs []smcheck.Counter) {
	cs = append([]smcheck.Counter(nil), cs...)
	sort.Slice(cs, func(i, j int) bool { return cs[i].Name < cs[j].Name })
	w.p("var %s = map[string]int{\n", name)
	for _, c := range cs {
		w.p("%q: %d,\n", c.Name, c.Cap)
	}
	w.p("}\n\n")
}

func (w *writer) stepTable(sp *smcheck.Spec) {
	w.p("// stepRows is step_table (table A), in file order.\n")
	w.p("var stepRows = []stepRow{\n")
	for _, r := range sp.Rows {
		w.p("{ID: %q, Event: %q, States: %s, Reason: %q, Types: %s, Stages: %s,\n", r.ID, r.Event,
			strs(r.States), r.Reason, strs(r.Types), strs(r.Stages))
		w.p("Guard: %s, To: %s, Effects: %s},\n", guards(r.Guard), target(r.To), strs(r.Effects))
	}
	w.p("}\n\n")

	w.p("// escRows expands the escalate pseudo-target.\n")
	w.p("var escRows = []escRow{\n")
	for _, e := range sp.Escalate {
		w.p("{Guard: %s, To: %s, Effects: %s},\n", guards(e.Guard), target(e.To), strs(e.Effects))
	}
	w.p("}\n\n")

	w.p("// ignoreEntries is the step-table ignored list.\n")
	w.p("var ignoreEntries = []ignoreEntry{\n")
	for _, i := range sp.Ignored {
		w.p("{States: %s, Events: %s, AllEvents: %t, Rule: %q},\n", strs(i.States), strs(i.Events), i.AllEvents, i.Rule)
	}
	w.p("}\n\n")
}

func (w *writer) holdTable(sp *smcheck.Spec) {
	w.p("// holdRows is req_hold.table (table B), in file order.\n")
	w.p("var holdRows = []holdRow{\n")
	for _, r := range sp.HoldRows {
		w.p("{ID: %q, Event: %q, From: %s, Guard: %s, To: %q, Effects: %s},\n", r.ID, r.Event,
			strs(r.From), guards(r.Guard), r.To, strs(r.Effects))
	}
	w.p("}\n\n")

	w.p("// holdEscRows expands the rescue_or_owner pseudo-target.\n")
	w.p("var holdEscRows = []holdEsc{\n")
	for _, e := range sp.HoldEscalate {
		w.p("{Guard: %s, To: %q, Effects: %s},\n", guards(e.Guard), e.To, strs(e.Effects))
	}
	w.p("}\n\n")

	w.p("// holdIgnores is req_hold.ignored.\n")
	w.p("var holdIgnores = []holdIgnore{\n")
	for _, i := range sp.HoldIgnored {
		w.p("{From: %s, Events: %s},\n", strs(i.From), strs(i.Events))
	}
	w.p("}\n")
}
