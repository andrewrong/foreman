package repocheck

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// sizeViolations implements C-03 for every Go package under root.
func sizeViolations(root string, lim limits) ([]string, error) {
	files, err := goFiles(root)
	if err != nil {
		return nil, err
	}
	nonTest := map[string]int{}
	test := map[string]int{}
	var out []string
	for _, f := range files {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(f)))
		if err != nil {
			return nil, err
		}
		if isGenerated(data) {
			continue
		}
		n := countLines(data)
		if n > lim.File {
			out = append(out, fmt.Sprintf("%s: %d lines > file limit %d", f, n, lim.File))
		}
		dir := path.Dir(f)
		if strings.HasSuffix(f, "_test.go") {
			test[dir] += n
		} else {
			nonTest[dir] += n
		}
	}
	for dir, n := range nonTest {
		if n > lim.NonTest {
			out = append(out, fmt.Sprintf("%s: %d non-test lines > %d", dir, n, lim.NonTest))
		}
	}
	for dir, n := range test {
		if n > lim.Test {
			out = append(out, fmt.Sprintf("%s: %d test lines > %d", dir, n, lim.Test))
		}
	}
	sort.Strings(out)
	return out, nil
}

func TestSizeLimits(t *testing.T) {
	root := repoRoot(t)
	m, err := loadModules(root)
	if err != nil {
		t.Fatal(err)
	}
	lim := m.PackageLimits
	if lim.NonTest <= 0 || lim.Test <= 0 || lim.File <= 0 {
		t.Fatalf("package_limits missing or invalid in %s: %+v", modulesPath, lim)
	}
	v, err := sizeViolations(root, lim)
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range v {
		t.Error(s)
	}
}

func TestSizeLimitsDetectsViolations(t *testing.T) {
	lim := limits{NonTest: 6, Test: 4, File: 5}
	body := func(n int) string { return "package p\n" + strings.Repeat("var _ = 1\n", n-1) }
	root := t.TempDir()
	writeFiles(t, root, map[string]string{
		"big/file.go":   body(8), // file limit
		"sum/a.go":      body(4), // 4+4 > 6
		"sum/b.go":      body(4),
		"tst/a_test.go": body(3), // 3+3 > 4
		"tst/b_test.go": body(3),
		"ok/a.go":       body(5),                                             // within limits
		"gen/gen.go":    "// Code generated by x. DO NOT EDIT.\n" + body(50), // excluded
	})
	v, err := sizeViolations(root, lim)
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(v, "\n")
	for _, want := range []string{"big/file.go: 8 lines", "sum: 8 non-test lines", "tst: 6 test lines"} {
		if !strings.Contains(joined, want) {
			t.Errorf("missing violation %q in:\n%s", want, joined)
		}
	}
	for _, bad := range []string{"ok", "gen/"} {
		if strings.Contains(joined, bad) {
			t.Errorf("unexpected violation mentioning %q:\n%s", bad, joined)
		}
	}
}
