#!/usr/bin/env ruby
# testtrace: build spec/tests.yaml from every test:/check: reference in spec/, and list active items with none (F4).
# Usage: ruby tools/testtrace.rb [--write]
require 'yaml'

refs = Hash.new { |h, k| h[k] = [] }   # test name -> [item ids]
uncovered = []

def names_in(v)
  v.to_s.scan(/\b((?:test|check):[a-z0-9][a-z0-9-]*)/).flatten.uniq
end

# coverage addenda (D-058 style): id -> "tests" | "none: reason" | "phase: v2"
cov = {}
YAML.load_file('spec/decisions.yaml')['decisions'].each do |d|
  cov.merge!(d['coverage']) if d['coverage'] && d['status'] != 'superseded'
end
deferred = []

# decisions and constitution: per item
{ 'spec/decisions.yaml' => 'decisions', 'spec/constitution.yaml' => nil }.each do |path, key|
  y = YAML.load_file(path)
  items = key ? y[key] : (y['articles'] || y['rules'] || y.values.find { |v| v.is_a?(Array) })
  items.each do |it|
    next if it['status'] == 'superseded'
    extra = cov[it['id']].to_s
    if extra.start_with?('none:', 'phase: v2')
      deferred << "#{it['id']} (#{extra})"
      next
    end
    ns = (names_in(it['enforced_by']) + names_in(extra)).uniq
    ns.each { |n| refs[n] << it['id'] }
    uncovered << it['id'] if ns.empty? && !it['enforced_by'].to_s.start_with?('sandbox')
  end
end

# design files and other spec files: any id-bearing hash
Dir['spec/design/*.yaml', 'spec/guardrails.yaml', 'spec/format-rules.yaml'].sort.each do |path|
  walk = lambda do |node, owner|
    case node
    when Hash
      id = node['id'] || owner
      node.each_value { |v| v.is_a?(String) ? names_in(v).each { |n| refs[n] << "#{File.basename(path, '.yaml')}:#{id}" } : walk.(v, id) }
    when Array then node.each { |v| v.is_a?(String) ? names_in(v).each { |n| refs[n] << "#{File.basename(path, '.yaml')}:#{owner}" } : walk.(v, owner) }
    end
  end
  walk.(YAML.load_file(path), File.basename(path, '.yaml'))
end

# A test:/check: name counts as implemented only if a Go test function with the
# mapped name exists (test:foo-bar / check:foo-bar -> TestFooBar).
src = Dir['**/*_test.go'].reject { |f| f.start_with?('.claude/') }.map { |f| File.read(f) }.join("\n")
not_in_code = refs.keys.sort.reject do |n|
  fn = 'Test' + n.split(':', 2)[1].split('-').map(&:capitalize).join
  src.include?("func #{fn}(")
end

out = {
  'schema' => 'foreman.tests/1',
  'note' => 'generated by tools/testtrace.rb from spec/; do not edit by hand. Each test or check must exist in code before v1 ships (phase: v2 items excepted).',
  'tests' => refs.keys.sort.map { |n| { 'name' => n, 'covers' => refs[n].uniq.sort } },
  'uncovered_active_items' => uncovered.sort,
  'not_testable_or_v2' => deferred.sort,
  'not_in_code' => not_in_code,
}
if ARGV.include?('--write')
  File.write('spec/tests.yaml', "# GENERATED — do not edit. Regenerate: ruby tools/testtrace.rb --write\n" + out.to_yaml)
end
puts "tests=#{out['tests'].size} uncovered=#{uncovered.size} not_in_code=#{not_in_code.size}"
puts "not in code: #{not_in_code.join(' ')}" unless not_in_code.empty?
puts "uncovered: #{uncovered.sort.join(' ')}" unless uncovered.empty?
